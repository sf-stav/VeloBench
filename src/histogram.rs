//! Distribution binning for the charts. The browser used to bin raw value
//! arrays itself (and the server had to ship those arrays, thousands of
//! numbers per live frame); the server now bins once and sends
//! `{min, max, counts}` — the painter only draws bars.
//!
//! Port of the former `drawHistogram` binning (identical bin edges/counts).

use serde_json::{json, Value};

#[derive(Clone, Debug, PartialEq)]
pub struct Histogram {
    pub min: f64,
    pub max: f64,
    pub counts: Vec<u32>,
}

pub struct Opts {
    /// Cap the x-axis here (values above clamp into the last bin).
    pub max: Option<f64>,
    /// Target bin width; otherwise a sqrt-rule bin count.
    pub bin_width: Option<f64>,
    pub max_bins: usize,
}

impl Opts {
    pub fn width(bin_width: f64) -> Self {
        Opts { max: None, bin_width: Some(bin_width), max_bins: 200 }
    }
    pub fn capped(mut self, max: Option<f64>) -> Self {
        self.max = max;
        self
    }
}

/// Bin `values` (empty input -> None).
pub fn histogram(values: &[f64], o: &Opts) -> Option<Histogram> {
    if values.is_empty() {
        return None;
    }
    let min = values.iter().cloned().fold(f64::INFINITY, f64::min);
    let abs_max = values.iter().cloned().fold(f64::NEG_INFINITY, f64::max);
    let capped = match o.max {
        Some(m) if m > min => m.min(abs_max),
        _ => abs_max,
    };
    let max = if capped == min { min + 1.0 } else { capped };
    let range = max - min;
    let range = if range == 0.0 { 1.0 } else { range };
    let bins = match o.bin_width.filter(|w| *w != 0.0) {
        Some(w) => (range / w + 0.5).floor() as i64,
        None => ((values.len() as f64).sqrt() * 2.0 + 0.5).floor().clamp(4.0, 48.0) as i64,
    };
    let bins = bins.clamp(4, o.max_bins.max(4) as i64) as usize;
    let bin_w = range / bins as f64;
    let mut counts = vec![0u32; bins];
    for v in values {
        let mut b = ((v - min) / bin_w).floor();
        if b < 0.0 {
            b = 0.0;
        }
        let b = (b as usize).min(bins - 1);
        counts[b] += 1;
    }
    Some(Histogram { min, max, counts })
}

impl Histogram {
    pub fn to_json(&self) -> Value {
        json!({ "min": self.min, "max": self.max, "counts": self.counts })
    }
}

pub fn hist_json(values: &[f64], o: &Opts) -> Value {
    histogram(values, o).map(|h| h.to_json()).unwrap_or(Value::Null)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_is_none() {
        assert!(histogram(&[], &Opts::width(1.0)).is_none());
    }

    #[test]
    fn fixed_bin_width_edges_and_counts() {
        // range 0..10 at width 2 => 5 bins: [0,2) [2,4) [4,6) [6,8) [8,10]
        let h = histogram(&[0.0, 1.9, 2.0, 5.0, 9.9, 10.0], &Opts::width(2.0)).unwrap();
        assert_eq!((h.min, h.max), (0.0, 10.0));
        assert_eq!(h.counts, vec![2, 1, 1, 0, 2]);
    }

    #[test]
    fn cap_clamps_outliers_into_the_last_bin() {
        let h = histogram(&[0.0, 1.0, 2.0, 3.0, 1000.0], &Opts::width(1.0).capped(Some(4.0))).unwrap();
        assert_eq!(h.max, 4.0);
        assert_eq!(h.counts.iter().sum::<u32>(), 5);
        assert_eq!(*h.counts.last().unwrap(), 2, "3.0 and the clamped 1000.0 share the last bin");
    }

    #[test]
    fn minimum_four_bins_and_degenerate_range() {
        let h = histogram(&[5.0, 5.0, 5.0], &Opts::width(10.0)).unwrap();
        assert_eq!((h.min, h.max), (5.0, 6.0));
        assert_eq!(h.counts.len(), 4);
        assert_eq!(h.counts[0], 3);
    }

    #[test]
    fn sqrt_rule_when_no_bin_width() {
        let values: Vec<f64> = (0..100).map(|i| i as f64).collect();
        let h = histogram(&values, &Opts { max: None, bin_width: None, max_bins: 200 }).unwrap();
        assert_eq!(h.counts.len(), 20, "round(sqrt(100) * 2)");
    }
}

#[cfg(test)]
mod differential {
    use super::*;

    /// Differential test against the original TypeScript binning. Cases are
    /// generated by a Node script that embeds that TypeScript verbatim:
    ///   HIST_CASES=/path/cases.json cargo test --release histogram_matches_reference -- --ignored
    #[test]
    #[ignore]
    fn histogram_matches_reference() {
        let path = std::env::var("HIST_CASES").expect("set HIST_CASES");
        let cases: Vec<Value> = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        let mut mismatches = 0;
        for (i, c) in cases.iter().enumerate() {
            let values: Vec<f64> = c["values"].as_array().unwrap().iter().map(|v| v.as_f64().unwrap()).collect();
            let o = &c["opts"];
            let opts = Opts {
                max: o["max"].as_f64(),
                bin_width: o["binWidth"].as_f64(),
                max_bins: o["maxBins"].as_u64().unwrap_or(200) as usize,
            };
            let got = histogram(&values, &opts).unwrap();
            let e = &c["expected"];
            let exp_counts: Vec<u32> = e["counts"].as_array().unwrap().iter().map(|v| v.as_u64().unwrap() as u32).collect();
            // serde_json's default float parser can be 1 ulp off on some decimals,
            // so edges are compared to 1e-12 relative; counts must be exact.
            let near = |a: f64, b: f64| (a - b).abs() <= 1e-12 * b.abs().max(1.0);
            let ok = near(got.min, e["min"].as_f64().unwrap()) && near(got.max, e["max"].as_f64().unwrap()) && got.counts == exp_counts;
            if !ok {
                mismatches += 1;
                eprintln!("case {i}: n={} opts={} got=({:?},{:?},{:?}) exp=({:?},{:?},{:?})", values.len(), o, got.min, got.max, got.counts, e["min"], e["max"], exp_counts);
            }
        }
        assert_eq!(mismatches, 0, "{} of {} cases differ from the TS reference", mismatches, cases.len());
    }
}
